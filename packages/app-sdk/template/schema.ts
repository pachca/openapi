import { defineSchema, defineTable, v } from "@pachca/app-sdk/server";

// Схема базы приложения: v.string(), v.number(), v.boolean(), v.id("таблица"), v.ref("таблица") (документ должен существовать), v.optional(...).
// Данные проверяет платформа. Таблицы, необязательные поля и индексы добавляются в любой момент.
// Обязательное поле, удаление поля и смена типа проходят, только если подходят все существующие данные,
// поэтому ломающее изменение делают в несколько версий: поле необязательное, мутация его заполняет, поле обязательное.
export default defineSchema({
  notes: defineTable({ text: v.string(), owner: v.string() }).index("by_owner", ["owner"]),
});
